#!/bin/sh
# usage: scripts/gen_langnames.sh <out.h>
# Emits the language table from po/LANGNAMES: one "<code> <name>" per line,
# '#' comments and blank lines ignored, name = everything after the first space.

out="$1"
names="$(dirname "$0")/../po/LANGNAMES"

{
    echo "// auto-generated by scripts/gen_langnames.sh -- do not edit"
    echo "struct language_entry {"
    echo "    const char *code;"
    echo "    const char *name;"
    echo "};"
    echo ""
    echo "static const struct language_entry languages[] = {"
    awk '
        /^[[:space:]]*(#|$)/ { next }
        {
            code = $1
            name = $0
            sub(/^[^[:space:]]+[[:space:]]*/, "", name)
            if (name == "") name = code
            printf "    { \"%s\", \"%s\" },\n", code, name
        }
    ' "$names"
    echo "    { NULL, NULL },"
    echo "};"
} > "$out.tmp"

# only touch the header when it actually changed (no cmp/diff in MSYS2 base)
if [ -f "$out" ] && [ "$(cat "$out")" = "$(cat "$out.tmp")" ]; then
    rm -f "$out.tmp"
else
    mv -f "$out.tmp" "$out"
fi